#!/usr/bin/env bash
# Installs local git config and the commit-standards hooks for this clone.
# Safe to re-run. Pre-existing hooks are kept as <hook>.local and still run.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
HOOKS_DIR=$(git rev-parse --git-path hooks)
MARKER="# commit-standards-hook"
mkdir -p "$HOOKS_DIR"

# --- Local git config -------------------------------------------------------
git config --local diff.renames true
git config --local diff.renameLimit 2000
git config --local apply.whitespace fix
git config --local core.autocrlf input
git config --local core.whitespace "trailing-space,space-before-tab"
# core.fileMode is left at the platform default: forcing it on Windows reports
# phantom mode changes. Executable bits are tracked in the index instead.

# --- Hook installation ------------------------------------------------------
install_hook() {
  local name="$1" target="$HOOKS_DIR/$1"
  if [ -f "$target" ] && ! grep -q "$MARKER" "$target"; then
    if [ -e "$target.local" ]; then
      echo "❌ $target.local already exists; resolve manually before re-running." >&2
      exit 1
    fi
    mv "$target" "$target.local"
    echo "↪ Kept existing $name hook as $name.local (chained)."
  fi
  cat > "$target"
  chmod +x "$target"
  echo "✅ Installed $name hook."
}

install_hook commit-msg <<'EOF'
#!/usr/bin/env bash
# commit-standards-hook
MSG=$(head -n 1 "$1")
PATTERN="^(feat|fix|refactor|perf|chore|test|docs|build|ci|model|data|eval|exp)(\([a-zA-Z0-9_-]+\))?: .{1,72}$"
# Messages generated by git itself (pull/merge/revert/autosquash) are exempt.
AUTOGEN='^(Merge |Revert "|fixup! |squash! |amend! )'

if ! echo "$MSG" | grep -Eq "$AUTOGEN" && ! echo "$MSG" | grep -Eq "$PATTERN"; then
  echo "❌ [Format Error] Invalid commit message: \"$MSG\""
  echo "Required: <type>(<scope>): <short imperative subject>"
  echo "Types: feat, fix, refactor, perf, chore, test, docs, build, ci, model, data, eval, exp"
  exit 1
fi

LOCAL_HOOK="$(dirname "$0")/commit-msg.local"
if [ -x "$LOCAL_HOOK" ]; then
  exec "$LOCAL_HOOK" "$@"
fi
EOF

install_hook pre-commit <<'EOF'
#!/usr/bin/env bash
# commit-standards-hook
set -e

# Initial commit has no HEAD; diff against the empty tree instead.
AGAINST=HEAD
git rev-parse --verify HEAD >/dev/null 2>&1 || AGAINST=$(git hash-object -t tree /dev/null)

# 1. Prevent trailing whitespace noise from being staged
if ! git diff-index --check --cached "$AGAINST" --; then
  echo "❌ [Whitespace Error] Staged changes contain trailing whitespace or newline artifacts."
  exit 1
fi

# 2. Check staged file count limit (excluding lockfiles, docs, git config)
EXCLUDED='(^|/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock|uv\.lock)$|\.md$|^\.gitattributes$|^\.editorconfig$'
STAGED_FILES=$(git diff --cached --name-only | { grep -Ev "$EXCLUDED" || true; } | wc -l)
MAX_FILES=5

if [ "$STAGED_FILES" -gt "$MAX_FILES" ]; then
  echo "❌ [Granularity Violation] Commit touches $STAGED_FILES files (Limit: $MAX_FILES)."
  echo "Split this work into smaller atomic commits."
  exit 1
fi

# 3. Block mixing configuration/infrastructure with application source
CONFIG_RE='(tsconfig|\.eslintrc|vite\.config|webpack|Dockerfile|\.env|CMakeLists\.txt)'
SRC_RE='^(src/|lib/|packages/|apps?/)'
HAS_CONFIG=$(git diff --cached --name-only | grep -E "$CONFIG_RE" || true)
HAS_SRC=$(git diff --cached --name-only | grep -Ev "$CONFIG_RE" | grep -E "$SRC_RE" || true)

if [ -n "$HAS_SRC" ] && [ -n "$HAS_CONFIG" ]; then
  echo "❌ [Isolation Violation] Staged changes mix build configuration and application source."
  echo "Commit configuration separately under 'chore(config): ...'."
  exit 1
fi

LOCAL_HOOK="$(dirname "$0")/pre-commit.local"
if [ -x "$LOCAL_HOOK" ]; then
  exec "$LOCAL_HOOK" "$@"
fi
EOF

echo "Done. Verify with: git config --local --list"
